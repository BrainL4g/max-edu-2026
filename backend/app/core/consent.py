POLICY_VERSION = "1.0"


def ai_assessment_enabled() -> bool:
    """Включена ли передача резюме внешнему сервису (GigaChat)."""
    return bool(settings.gigachat_credentials or settings.gigachat_access_token)


def consent_timestamp() -> datetime:
    """Момент фиксации согласия (UTC, без tzinfo — как в остальных колонках)."""
    return datetime.now(UTC).replace(tzinfo=None)


