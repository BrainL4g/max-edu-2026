THIRD_PARTY_ON = """Оценку резюме выполняет внешний сервис искусственного интеллекта
GigaChat (ПАО Сбербанк) — третье лицо по отношению к оператору.
При разборе резюме ему передаются:
- текст резюме, который вы прислали, — не более 8000 символов;
- найденные навыки;
- выбранное вами направление обучения.
Адрес: api.giga.chat (домены sberbank.ru и giga.chat). Оператором передачи
выступает ПАО Сбербанк, который обрабатывает данные на своих серверах в
соответствии со своей политикой конфиденциальности. Дополнительно модель
возвращает оценку готовности резюме по шкале 0–100 и краткий вердикт;
результат сохраняется вместе с разбором."""

THIRD_PARTY_OFF = """AI-оценка резюме не подключена. Текст резюме разбирается
только на сервере оператора и за его пределы не передаётся."""


def policy_text(ai_enabled: bool | None = None) -> str:
    """Текст политики под текущую конфигурацию.

    ``ai_enabled`` — результат :func:`ai_assessment_enabled`, если не передан
    явно. Формулировка о передаче третьему лицу всегда безусловная: при
    включённой AI-оценке сказано, что передача происходит, при выключенной —
    что не происходит.
    """
    enabled = ai_assessment_enabled() if ai_enabled is None else ai_enabled
    third_party = THIRD_PARTY_ON if enabled else THIRD_PARTY_OFF
    return POLICY_TEMPLATE.format(third_party=third_party)
